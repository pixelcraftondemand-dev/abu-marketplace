/**
 * Detects Sierra Leone Mobile Money carrier from phone input
 */
export function detectCarrier(rawPhone: string): {
  carrier: 'orange' | 'afrimoney' | null;
  name: string;
  badgeColor: string;
  ussdCode: string;
} {
  const cleaned = rawPhone.replace(/\D/g, '');
  // Sierra Leone local format starts with 07, 08, 09, 03 or international 2327, 2328, 2329, 2323
  let localPrefix = '';
  if (cleaned.startsWith('232')) {
    localPrefix = '0' + cleaned.substring(3, 5);
  } else if (cleaned.length >= 3) {
    localPrefix = cleaned.substring(0, 3);
  } else if (cleaned.length >= 2) {
    localPrefix = cleaned.substring(0, 2);
  }

  // Orange prefixes: 072, 073, 074, 075, 076, 078, 079, 07
  if (localPrefix.startsWith('07') && !localPrefix.startsWith('077')) {
    return {
      carrier: 'orange',
      name: 'Orange Money',
      badgeColor: '#FF6600',
      ussdCode: '*144#',
    };
  }

  // Afrimoney (Africell) prefixes: 088, 080, 030, 033, 099, 077, 08, 03, 09
  if (
    localPrefix.startsWith('08') ||
    localPrefix.startsWith('03') ||
    localPrefix.startsWith('09') ||
    localPrefix.startsWith('077')
  ) {
    return {
      carrier: 'afrimoney',
      name: 'Afrimoney (Africell)',
      badgeColor: '#7A1CAC',
      ussdCode: '*161#',
    };
  }

  return {
    carrier: null,
    name: 'Select Provider',
    badgeColor: '#5A6872',
    ussdCode: '',
  };
}

export function formatSLE(amount: number): { prefix: string; value: string } {
  return {
    prefix: 'SLE',
    value: new Intl.NumberFormat('en-US').format(amount),
  };
}

